package dev.irv.authonly;

import static dev.irv.authonly.AuthAudit.*;

import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import java.io.IOException;
import java.net.HttpURLConnection;
import java.net.Proxy;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.*;
import org.apache.catalina.connector.Connector;
import org.springframework.boot.web.embedded.tomcat.TomcatServletWebServerFactory;
import org.springframework.boot.web.server.WebServerFactoryCustomizer;
import org.springframework.boot.web.servlet.FilterRegistrationBean;
import org.springframework.context.annotation.*;
import org.springframework.core.Ordered;
import org.springframework.core.env.Environment;
import org.springframework.core.io.ClassPathResource;

/** Mandatory admission boundary in every profile; unfinished routes remain inaccessible. */
@Configuration(proxyBeanMethods = false)
public class ApplicationBoundaryConfiguration {
  private final AuthSettings settings;
  private final CertificateGate gate;
  private final BoundSessions sessions;
  private final boolean tunnelEnabled;

  public ApplicationBoundaryConfiguration(Environment env, AuthSettings settings, CertificateGate gate, BoundSessions sessions) {
    this.settings = settings; this.gate = gate; this.sessions = sessions;
    tunnelEnabled = Boolean.parseBoolean(env.getProperty("IRV_TUNNEL_ENABLED", "false"));
  }

  @Bean
  WebServerFactoryCustomizer<TomcatServletWebServerFactory> applicationConnector() {
    return factory -> {
      Connector connector = new Connector(TomcatServletWebServerFactory.DEFAULT_PROTOCOL);
      connector.setPort(8081);
      connector.setProperty("address", "127.0.0.1");
      factory.addAdditionalTomcatConnectors(connector);
    };
  }

  record Check(String id, String label, String status, String detail) {}

  private static Check check(String id, String label, String status, String detail) {
    return new Check(id, label, status, detail);
  }

  Map<String, Object> report(HttpServletRequest request) {
    String fp = settings.certificateRequired ? gate.verified(request) : null;
    boolean approved = gate.approved(request) != null;
    BoundSessions.Bound bound = sessions.current(request);
    String pending = bound != null ? "passed" : "pending";
    List<Check> checks = List.of(
        check("spring", "Spring connectivity", "passed", "Generated by the backend."),
        check("certificate", "Cloudflare certificate evidence", !settings.certificateRequired ? "not_required" : settings.ingressSecret.isEmpty() ? "not_configured" : fp != null ? "passed" : "failed",
            settings.certificateRequired ? "Trusted Cloudflare evidence must report a valid, non-revoked certificate." : "Operator disabled certificate admission; copied-cookie protection from mTLS no longer applies."),
        check("approval", "Trusted application ingress", settings.ingressSecret.isEmpty() ? "not_configured" : approved ? "passed" : "failed",
            "Loopback ingress and forwarding secret required. No permanent certificate/account mapping."),
        check("token", "ZITADEL ID token and login transaction", pending,
            "Signature, issuer, audience, expiry, state, nonce and PKCE must pass before a session is created."),
        check("passkey", "Fresh verified passkey", pending,
            "Requires signed user + mfa evidence without password/OTP and authentication after login began."),
        check("admission", "Account role", pending,
            "Verified ID token must carry irv_user in the configured organization. Invited signup provisions this role."),
        check("match", "Session identity binding", pending,
            settings.certificateRequired ? "The verified account and exact presented certificate are bound only for this session." : "Session is bound to the verified account; certificate binding is disabled."),
        check("session", "Current authenticated session", pending,
            "5-minute idle and 8-hour absolute expiry. Background checks do not extend it."));
    Map<String, Object> result = new LinkedHashMap<>();
    result.put("authenticated", bound != null);
    result.put("checks", checks); result.put("overall", bound != null ? "Authenticated" : "Authentication incomplete");
    result.put("checkedAt", java.time.Instant.now().toString());
    result.put("sandboxAccessEnabled", false);
    AuthAudit.Reason signupReason = settings.signupAvailability(java.time.Instant.now());
    audit(Stage.SIGNUP_AVAILABILITY, signupReason == Reason.VALID ? Outcome.PASSED : Outcome.FAILED, signupReason);
    result.put("signupEnabled", signupReason == Reason.VALID);
    result.put("certificateRequired", settings.certificateRequired);
    if (bound != null) {
      result.put("idleExpiresAt", bound.activity().plus(BoundSessions.IDLE).toString());
      result.put("absoluteExpiresAt", bound.created().plus(BoundSessions.ABSOLUTE).toString());
    }
    return result;
  }

  private boolean ready() {
    if (!tunnelEnabled) return true;
    HttpURLConnection connection = null;
    try {
      connection =
          (HttpURLConnection)
              URI.create("http://127.0.0.1:2000/ready").toURL().openConnection(Proxy.NO_PROXY);
      connection.setConnectTimeout(1000);
      connection.setReadTimeout(1000);
      connection.setInstanceFollowRedirects(false);
      return connection.getResponseCode() == 200;
    } catch (IOException e) {
      return false;
    } finally {
      if (connection != null) connection.disconnect();
    }
  }

  @Bean
  FilterRegistrationBean<jakarta.servlet.Filter> applicationBoundary(ObjectMapper mapper)
      throws IOException {
    Map<String, byte[]> assets = new HashMap<>();
    for (String name : List.of("index.html", "diagnostics.html", "app.js", "style.css")) {
      try (var input = new ClassPathResource("authentication/" + name).getInputStream()) {
        assets.put(name, input.readAllBytes());
      }
    }
    FilterRegistrationBean<jakarta.servlet.Filter> registration = new FilterRegistrationBean<>();
    registration.setOrder(Ordered.HIGHEST_PRECEDENCE + 1);
    registration.addUrlPatterns("/*");
    registration.setDispatcherTypes(
        jakarta.servlet.DispatcherType.REQUEST,
        jakarta.servlet.DispatcherType.ASYNC,
        jakarta.servlet.DispatcherType.ERROR,
        jakarta.servlet.DispatcherType.FORWARD,
        jakarta.servlet.DispatcherType.INCLUDE);
    registration.setFilter(
        (req, res, chain) -> {
          HttpServletRequest request = (HttpServletRequest) req;
          HttpServletResponse response = (HttpServletResponse) res;
          response.setHeader("Cache-Control", "no-store");
          response.setHeader("X-Content-Type-Options", "nosniff");
          response.setHeader("Referrer-Policy", "no-referrer");
          response.setHeader(
              "Content-Security-Policy",
              "default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'self';"
                  + " frame-ancestors 'none'; base-uri 'none'; form-action 'self'");
          response.setHeader("X-Frame-Options", "DENY");
          String path = request.getRequestURI();
          boolean read = Set.of("GET", "HEAD").contains(request.getMethod());
          byte[] body = null;
          String type = "application/json;charset=UTF-8";
          if (request.getLocalPort() == 8080 && path.equals("/api/health")) {
            if (!read) {
              audit(Stage.ROUTE, Outcome.FAILED, Reason.METHOD_NOT_ALLOWED);
              response.setStatus(405);
              response.setHeader("Allow", "GET, HEAD");
              return;
            }
            boolean healthy = ready();
            response.setStatus(healthy ? 200 : 503);
            body = mapper.writeValueAsBytes(Map.of("status", healthy ? "ok" : "unavailable"));
          } else if (request.getLocalPort() == 8081
              && Set.of("/", "/auth/diagnostics", "/auth/status", "/auth/app.js", "/auth/style.css").contains(path)) {
            if (!read) {
              audit(Stage.ROUTE, Outcome.FAILED, Reason.METHOD_NOT_ALLOWED);
              response.setStatus(405);
              response.setHeader("Allow", "GET, HEAD");
              return;
            }
            if (gate.approved(request) == null) {
              sessions.current(request);
              response.setStatus(403); return;
            }
            if (path.equals("/auth/status")) body = mapper.writeValueAsBytes(report(request));
            else {
              String name = path.equals("/") ? "index.html" : path.equals("/auth/diagnostics") ? "diagnostics.html" : path.substring("/auth/".length());
              body = assets.get(name);
              type =
                  name.endsWith("html")
                      ? "text/html;charset=UTF-8"
                      : name.endsWith("js")
                          ? "text/javascript;charset=UTF-8"
                          : "text/css;charset=UTF-8";
            }
          } else if (request.getLocalPort() == 8081 && Set.of(
              "/auth/signup", "/auth/signup/resume", "/auth/csrf", "/auth/protected", "/auth/activity", "/auth/logout",
              "/auth/login", "/login/oauth2/code/zitadel").contains(path)) {
            boolean post = Set.of("/auth/signup", "/auth/signup/resume", "/auth/activity", "/auth/logout", "/auth/login").contains(path);
            if (!(post ? "POST" : "GET").equals(request.getMethod())) {
              audit(Stage.ROUTE, Outcome.FAILED, Reason.METHOD_NOT_ALLOWED);
              response.setStatus(405); return;
            }
            if (gate.approved(request) == null) {
              // A stolen cookie from another device does not pass the certificate gate.
              sessions.current(request);
              response.setStatus(403); return;
            }
            if (post && !AuthSettings.ORIGIN.equals(CertificateGate.header(request, "Origin"))) {
              audit(Stage.ORIGIN, Outcome.FAILED, Reason.INVALID_ORIGIN);
              response.setStatus(403); return;
            }
            if (post) audit(Stage.ORIGIN, Outcome.PASSED, Reason.VALID);
            if (Set.of("/auth/protected", "/auth/activity", "/auth/logout").contains(path)
                && sessions.current(request) == null) {
              response.setStatus(401); return;
            }
            chain.doFilter(request, response);
            return;
          } else {
            audit(Stage.ROUTE, Outcome.FAILED, Reason.ROUTE_NOT_EXPOSED);
            response.setStatus(404);
            return;
          }
          response.setContentType(type);
          response.setContentLength(body.length);
          if (!request.getMethod().equals("HEAD")) response.getOutputStream().write(body);
          // Terminal allowlist: never dispatch to legacy controllers, assets, error pages or
          // WebSockets.
        });
    return registration;
  }
}
